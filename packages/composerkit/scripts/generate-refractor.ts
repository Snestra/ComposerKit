// Writes src/components/diff/syntax-refractor.js from refractor/core. Run it
// after a refractor upgrade and commit the file.
//
//   pnpm --filter composerkit generate:refractor

import { fileURLToPath } from "node:url";

import { build } from "vite";

const root = fileURLToPath(new URL("..", import.meta.url));

// The registry compiles the TypeScript worker itself. Ship a worker-safe core
// so its transitive entity decoder never selects a DOM-only browser export.
await build({
  build: {
    copyPublicDir: false,
    emptyOutDir: false,
    lib: {
      entry: fileURLToPath(import.meta.resolve("refractor/core")),
      formats: ["es"],
    },
    minify: false,
    outDir: `${root}/src/components/diff`,
    rolldownOptions: {
      output: {
        banner:
          "// Generated by packages/composerkit/scripts/generate-refractor.ts. Do not edit.",
        codeSplitting: false,
        entryFileNames: "syntax-refractor.js",
      },
    },
  },
  configFile: false,
  resolve: { conditions: ["worker"] },
});
