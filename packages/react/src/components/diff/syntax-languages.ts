// oxlint-disable-next-line eslint/prefer-named-capture-group -- the tsconfig target predates named capture groups
const COMPOUND_EXTENSION = /\.([^/\\]+\.[^/\\]+)$/u;

// oxlint-disable-next-line eslint/prefer-named-capture-group -- the tsconfig target predates named capture groups
const EXTENSION = /\.([^.]+)$/u;
const PATH_SEPARATOR = /[/\\]/u;

/** The language of a path or file name; null when nothing matches. */
const languageForKey = (key: string): string | null => {
  const whole = FILE_NAME_LANGUAGES.get(key);

  if (whole !== undefined) {
    return whole;
  }

  const compound = COMPOUND_EXTENSION.exec(key)?.[1];

  if (compound !== undefined && FILE_NAME_LANGUAGES.has(compound)) {
    return FILE_NAME_LANGUAGES.get(compound) ?? "text";
  }

  return FILE_NAME_LANGUAGES.get(EXTENSION.exec(key)?.[1] ?? "") ?? null;
};

/** The language of a file name; "text" when nothing matches. */
export const languageForFileName = (name: string): string => {
  const whole = languageForKey(name);

  if (whole !== null) {
    return whole;
  }

  const base = name.split(PATH_SEPARATOR).pop() ?? name;

  return base === name ? "text" : (languageForKey(base) ?? "text");
};
